"""Screening rules and filter models, free of I/O.

This module is the package's public API. Consumers import from the package root
only::

    from domain import build_company_metrics, evaluate_eligibility

Everything re-exported here is a supported contract. Anything not listed in
`__all__` is internal and may change without a version bump.

The package holds four things: the normalised models every other layer speaks in
(`models`, `scores`), the deterministic metric engine (`metrics`), the
eligibility screen with its universe rules (`eligibility`, `universe`), and
CompounderScore v1 (`scoring`, `curves`, `sectors`). None of them perform I/O, so
all of them are testable against hand-worked numbers.
"""

