"""The SEC evidence corpus: where documents are stored, and what proves it.

Four pieces, each with one job. `storage` decides where an artifact belongs and
writes it atomically onto a root that must already exist. `manifest` is the
append-only provenance log. `harvest` fetches what is not already provably held,
within a budget, and records every outcome. `sample` chooses a reproducible
batch of securities to read.

The rule the whole subsystem is built around: **an evidence root on an unmounted
drive must fail loudly, never quietly become a directory on the boot disk.**
"""

